import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const dist = path.join(root, "dist");
const output = path.join(dist, "service-worker.js");
const excluded = new Set([".nojekyll", "service-worker.js"]);

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(fullPath) : [fullPath];
  });
}

const files = walk(dist)
  .map((file) => path.relative(dist, file).replaceAll("\\", "/"))
  .filter((file) => !excluded.has(file))
  .sort();

const digest = crypto.createHash("sha256");
for (const file of files) {
  digest.update(file);
  digest.update(fs.readFileSync(path.join(dist, file)));
}
const version = digest.digest("hex").slice(0, 12);
const assets = ["./", ...files.map((file) => `./${file}`)];

const source = `// Generated by scripts/generate-service-worker.mjs. Do not edit by hand.
const CACHE_NAME = "avop-study-${version}";
const OFFLINE_ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(OFFLINE_ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names.filter((name) => name.startsWith("avop-study-") && name !== CACHE_NAME).map((name) => caches.delete(name))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => response.ok ? response : Promise.reject(new Error("Navigation failed")))
        .catch(() => caches.match("./index.html"))
    );
    return;
  }

  event.respondWith(caches.match(request, { ignoreSearch: true }).then((cached) => cached || fetch(request)));
});
`;

fs.writeFileSync(output, source);
console.log(`Generated ${path.relative(root, output)} with ${assets.length} offline resources (${version}).`);
